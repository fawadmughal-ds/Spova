import type { Metadata } from 'next';
import Link from 'next/link';
import { notFound } from 'next/navigation';
import { ArrowLeft, Download, FileText } from 'lucide-react';
import { LEGAL_DOCS, legalDoc, legalText } from '@spova/shared';
import { BRAND } from '@/lib/utils';
import { buttonClass } from '@/lib/button';
import { PageHero } from '@/components/marketing/page-hero';
import { Reveal } from '@/components/motion';

export const dynamicParams = false;
export function generateStaticParams() {
  return LEGAL_DOCS.map((d) => ({ slug: d.slug }));
}
export async function generateMetadata({ params }: { params: Promise<{ slug: string }> }): Promise<Metadata> {
  const { slug } = await params;
  const d = legalDoc(slug);
  return { title: d ? `${d.title} · ${BRAND}` : 'Legal document', description: d ? legalText(d.note, BRAND) : undefined };
}

/** Online version of one legal document; the PDF is the same text, generated by scripts/build-legal-pdfs.mjs. */
export default async function LegalDocumentPage({ params }: { params: Promise<{ slug: string }> }) {
  const { slug } = await params;
  const d = legalDoc(slug);
  if (!d) notFound();
  const i = LEGAL_DOCS.findIndex((x) => x.slug === slug);
  return (
    <>
      <PageHero
        eyebrow={`Legal · ${d.group}`}
        title={d.title}
        lead={<p>{legalText(d.note, BRAND)}</p>}
        actions={
          <div className="flex flex-col gap-3">
            <a href={`/legal/${d.slug}.pdf`} download className={buttonClass('primary', 'lg')}>
              <Download className="h-4 w-4" /> Download PDF
            </a>
            <div className="font-mono text-[11px] uppercase tracking-[0.14em] text-ink-400">
              {d.version} · {d.effective}
            </div>
          </div>
        }
      />
      <section className="mx-auto max-w-7xl px-4 pb-24 sm:px-6">
        <div className="grid gap-10 lg:grid-cols-[260px_1fr]">
          <aside className="lg:sticky lg:top-28 lg:self-start">
            <Link href="/legal" className="group inline-flex items-center gap-2 text-sm text-ink-400 transition-colors hover:text-white">
              <ArrowLeft className="h-4 w-4 transition-transform duration-300 group-hover:-translate-x-1" /> All documents
            </Link>
            <nav className="mt-6 space-y-1" aria-label="Legal documents">
              {LEGAL_DOCS.map((x) => (
                <Link key={x.slug} href={`/legal/${x.slug}`} aria-current={x.slug === slug ? 'page' : undefined} className={`block rounded-lg px-3 py-2 text-sm transition-colors ${x.slug === slug ? 'bg-brand-400/10 font-medium text-white' : 'text-ink-400 hover:bg-white/[0.04] hover:text-white'}`}>
                  {x.title}
                </Link>
              ))}
            </nav>
          </aside>
          <Reveal variant="fade" className="card p-6 sm:p-10">
            <div className="flex items-center gap-3 border-b border-white/[0.06] pb-5 font-mono text-[11px] uppercase tracking-[0.14em] text-ink-500">
              <FileText className="h-4 w-4 text-brand-300" /> Document {String(i + 1).padStart(2, '0')} · {d.version} · {d.effective}
            </div>
            <div className="prose-legal mt-6 space-y-8">
              {d.sections.map((s) => (
                <section key={s.h}>
                  <h2 className="font-display text-xl font-bold tracking-tight">{s.h}</h2>
                  {s.p.map((p, k) => (
                    <p key={k} className="mt-3 leading-relaxed text-ink-300">
                      {legalText(p, BRAND)}
                    </p>
                  ))}
                </section>
              ))}
            </div>
            <p className="mt-10 rounded-xl bg-white/[0.03] px-4 py-3 text-xs leading-relaxed text-ink-400 ring-1 ring-inset ring-white/[0.06]">
              This document forms part of the Legal Documents of {BRAND}. The current version is always the one published on this page. CFDs are complex instruments and come with a high risk of losing money rapidly due to leverage.
            </p>
          </Reveal>
        </div>
      </section>
    </>
  );
}
